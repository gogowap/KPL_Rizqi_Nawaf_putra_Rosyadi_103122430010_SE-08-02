/**
 * Fungsi untuk menambahkan jumlah tertentu pada penghitung (counter).
 * @param {number} terkini - Nilai penghitung saat ini
 * @param {number} jumlah - Jumlah yang ingin ditambahkan
 * @returns {number} Hasil penjumlahan
 */
export function tambahPengitung(terkini, jumlah) {
  return terkini + jumlah;
}